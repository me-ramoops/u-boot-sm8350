static ulong sm8350_set_rate(struct clk *clk, ulong rate)
{
	struct msm_clk_priv *priv = dev_get_priv(clk->dev);
	const struct freq_tbl *freq;

	if (clk->id < priv->data->num_clks)
		debug("%s: %s, requested rate=%ld\n", __func__,
		      priv->data->clks[clk->id].name, rate);

	switch (clk->id) {
	case GCC_QUPV3_WRAP0_S3_CLK: /*UART2*/
		freq = qcom_find_freq(ftbl_gcc_qupv3_wrap0_s3_clk_src, rate);
		clk_rcg_set_rate_mnd(priv->base, GCC_QUPV3_WRAP0_S3_CLK_SRC_REG,
				     freq->pre_div, freq->m, freq->n, freq->src,
				     16);

		return freq->freq;
	default:
		return 0;
	}
}

